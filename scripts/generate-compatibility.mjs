/** Generate a guarded public Host entry and proof from the attested, built source. */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, matchesGlob, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import { requirePreparedHarness } from './harness-source.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { harnessRoot, lock } = requirePreparedHarness(root)
const output = join(root, 'packages/domain/lib')
const workspace = new Map()
function indexPackages(parent, nested = false) {
  for (const child of readdirSync(join(harnessRoot, parent), { withFileTypes: true })) {
    if (!child.isDirectory()) continue
    const directory = `${parent}/${child.name}`
    if (nested) indexPackages(directory)
    else if (existsSync(join(harnessRoot, directory, 'package.json'))) {
      const manifest = JSON.parse(readFileSync(join(harnessRoot, directory, 'package.json'), 'utf8'))
      workspace.set(manifest.name, { directory: join(harnessRoot, directory), manifest })
    }
  }
}
indexPackages('vendor')
indexPackages('packages', true)
for (const name of ['codex', 'claude-code']) {
  const directory = join(root, 'packages', name)
  const manifest = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'))
  workspace.set(manifest.name, { directory, manifest })
}
const hostManifest = JSON.parse(readFileSync(join(root, 'packages/domain/package.json'), 'utf8'))
const profileManifest = JSON.parse(readFileSync(join(root, 'packages/profile/package.json'), 'utf8'))
const roots = {
  host: Object.keys(hostManifest.peerDependencies).filter(name => workspace.has(name)),
  profile: Object.keys(profileManifest.peerDependencies).filter(name => workspace.has(name)),
}
const packages = {}
const pending = [...roots.host, ...roots.profile]
while (pending.length) {
  const name = pending.shift()
  if (name in packages) continue
  const { directory, manifest } = workspace.get(name)
  const packageRoot = directory
  const files = {}
  for (const file of readdirSync(join(packageRoot, 'lib'), { recursive: true }).sort()) {
    if (!file.endsWith('.js')) continue
    const path = `lib/${file}`
    if (manifest.files && path !== manifest.main && !manifest.files.some(pattern =>
      matchesGlob(path, pattern) || path.startsWith(`${pattern.replace(/\/$/, '')}/`))) continue
    files[path] = createHash('sha256').update(readFileSync(join(packageRoot, path))).digest('hex')
  }
  packages[manifest.name] = {
    version: manifest.version, main: manifest.main, exports: manifest.exports, files,
    dependencies: Object.keys({ ...manifest.dependencies, ...manifest.peerDependencies })
      .filter(name => workspace.has(name) && !manifest.peerDependenciesMeta?.[name]?.optional),
    products: Object.values(lock.compatibility.nativeProducts)
      .filter(product => product.package in (manifest.dependencies ?? {}))
      .map(product => ({
        name: product.package,
        fields: {
          version: product.version,
          ...(product.package === '@anthropic-ai/claude-agent-sdk' ? { claudeCodeVersion: product.nativePayload } : {}),
        },
      })),
  }
  pending.push(...packages[manifest.name].dependencies)
}
writeFileSync(join(output, 'compatibility.json'), `${JSON.stringify({
  schemaVersion: 1,
  maintainedFork: lock.upstream,
  ...lock.compatibility,
  retiredRuntimePackages: [
    '@deepseek-ai/dsh-experimental-agent-team-codex',
    '@deepseek-ai/dsh-experimental-agent-team-claude-code',
  ],
  roots,
  packages,
}, null, 2)}\n`)

const host = ts.createSourceFile('host.js', readFileSync(join(output, 'host.js'), 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
const exports = host.statements.filter(ts.isExportDeclaration).flatMap(statement => {
  if (statement.moduleSpecifier || !statement.exportClause || !ts.isNamedExports(statement.exportClause)) {
    throw new Error('generate-compatibility: Host bundle must expose a concrete named export list')
  }
  return statement.exportClause.elements.map(element => element.name.text)
})
if (!exports.includes('DigitalEmployeeService') || !exports.includes('default')) {
  throw new Error('generate-compatibility: Host bundle is missing its public service')
}
writeFileSync(join(output, 'index.js'), [
  '// Generated by scripts/generate-compatibility.mjs. Do not edit.',
  "import { assertUltraCompatibility } from './compatibility.js'",
  'assertUltraCompatibility(import.meta.url)',
  "const implementation = await import('./host.js')",
  ...exports.map(name => name === 'default' ? 'export default implementation.default' : `export const ${name} = implementation.${name}`),
  '',
].join('\n'))
